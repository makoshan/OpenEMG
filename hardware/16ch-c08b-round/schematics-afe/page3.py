"""C08B 采集板 第 3 页：模拟电源。只有 ±2.5V 电荷泵（LM27762）在采集板；3V3 由主控板经 J_AFE 供入。
充电（TP4054）、开关机、3V3 稳压、USB 联锁都在主控板，不画在本页。"""
import json
from sch import *

PAGE_REFS = ['C901', 'C902', 'D901', 'R901', 'V4_C50', 'V4_C81', 'V4_C82', 'V4_C83', 'V4_C84', 'V4_LM27762', 'V4_R26', 'V4_R27', 'V4_R28', 'V4_R29']

# ---------------- A 3V3 输入（来自主控板 J_AFE） ----------------
block(30, 60, 840, 300, 'A  3V3 输入：主控板经 J_AFE 供入', '主控板生成 3V3，经板对板座供入采集板；C901 本地去耦；3V3 下送 B 框电荷泵')
pwr('3V3', 150, 150)
cap('C901', 150, 210, 'vr'); gnd(*Pn('C901', '1')); wire(Pn('C901', '2'), (150, 150))
text('3V3 → ±2.5V 电荷泵（下框 B）；充电/开关机/3V3 稳压在主控板', 230, 155, color='#555')

# ---------------- D ±2.5V 模拟双电源 ----------------
block(30, 560, 840, 1080, 'B  ±2.5V 模拟双电源：LM27762，3V3 → ±2.5V', '电荷泵产生负压，正负两路 LDO 输出，分压电阻定 ±2.5V；PGOOD 拉低时绿灯亮')
U = 'V4_LM27762'
ic(U, 330, 700, 180, 330, [
    ('3', 'VIN', 'L', 30), ('12', 'EN+', 'L', 60), ('8', 'EN-', 'L', 90), ('5', 'CP', 'L', 150), ('10', 'C1+', 'L', 210), ('9', 'C1-', 'L', 290),
    ('1', 'PGOOD', 'T', 150), ('11', 'OUT+', 'R', 30), ('2', 'FB+', 'R', 110), ('6', 'OUT-', 'R', 220), ('7', 'FB-', 'R', 300),
    ('4', 'GND', 'B', 60), ('13', 'EP', 'B', 120)])
pwr('3V3', 90, 730); wire((90, 730), Pn(U, '3'))
cap('V4_C81', 150, 770, 'vr'); cap('V4_C82', 210, 770, 'vr'); gnd(*Pn('V4_C81', '1')); gnd(*Pn('V4_C82', '1'))
wire((270, 730), (270, 790)); wire((270, 760), Pn(U, '12')); wire((270, 790), Pn(U, '8'))
text('EN± 接 VIN：常开', 60, 690, color='#555')
cap('C902', 180, 890, 'vr'); wire(Pn(U, '5'), Pn('C902', '2')); gnd(*Pn('C902', '1'))
cap('V4_C50', 250, 950, 'vr'); wire(Pn(U, '10'), Pn('V4_C50', '2')); wire(Pn(U, '9'), Pn('V4_C50', '1'))
text('飞跨电容', 200, 1030, color='#555')
wire(Pn(U, '4'), (390, 1060), (450, 1060), Pn(U, '13')); gnd(420, 1060)
# 正输出：OUT+ → 分压 R26/R27 回 FB+
wire(Pn(U, '11'), (800, 730)); pwr('V4_+2.5V', 800, 730)
res('V4_R26', 600, 770, 'vr'); res('V4_R27', 600, 850, 'vr')
wire(Pn(U, '2'), Pn('V4_R26', '1')); gnd(*Pn('V4_R27', '1'))
cap('V4_C83', 700, 770, 'vr'); gnd(*Pn('V4_C83', '1'))
# 负输出：OUT- → 分压 R29/R28 回 FB-
wire(Pn(U, '6'), (800, 920)); pwr('V4_-2.5V', 800, 920)
res('V4_R29', 640, 960, 'v'); res('V4_R28', 690, 1000, 'h')
wire(Pn(U, '7'), Pn('V4_R29', '2'), Pn('V4_R28', '1')); gnd(*Pn('V4_R28', '2'))
cap('V4_C84', 770, 960, 'vr'); gnd(*Pn('V4_C84', '1'))
# PGOOD 指示灯
wire(Pn(U, '1'), (480, 650), (540, 650))
diode('D901', 580, 650, 'left', '2', '1', led=True); res('R901', 700, 650, 'hr')
wire(Pn('D901', '2'), Pn('R901', '2')); pwr('3V3', *Pn('R901', '1'))

finish(3, '模拟电源', PAGE_REFS, 'C08B 采集板 模拟电源：3V3（经 J_AFE 自主控板）→ LM27762 → ±2.5V 供两颗 ADS',
       '充电 / 开关机 / 3V3 稳压 / USB 联锁均在主控板；本页只留采集板自带的 ±2.5V 电荷泵与 3V3 去耦。')
