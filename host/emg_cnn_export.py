"""Turn the trained 4-channel EMG CNN (emg_gni_train.py --save) into C headers for the XIAO bench.

BatchNorm is folded into the conv weights, so the board runs conv -> ReLU only. The same folded
weights are run here in numpy and must match the PyTorch logits on the saved probe windows; the
header carries those windows and logits so the board is checked against the same numbers.

    python emg_cnn_export.py emg-public/gni_4ch_3g.pt      # writes device/emg_cnn_weights.h + device/emg_cnn_input.h
    python emg_cnn_export.py --check                       # random net: fold + numpy forward == torch forward
"""
import argparse
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
LAYERS = ((9, 32), (7, 64), (5, 64), (5, 64))       # kernel, out channels; stride 2, pad k//2, like Net


def fold(state):
    """[(w (o,i,k), b (o,))] with BN folded; then (head_w (n,64), head_b (n,))."""
    convs = []
    for l in range(4):
        w, b = state[f'f.{l}.0.weight'].numpy(), state[f'f.{l}.0.bias'].numpy()
        g, beta = state[f'f.{l}.1.weight'].numpy(), state[f'f.{l}.1.bias'].numpy()
        mean, var = state[f'f.{l}.1.running_mean'].numpy(), state[f'f.{l}.1.running_var'].numpy()
        s = g / np.sqrt(var + 1e-5)
        convs.append((w * s[:, None, None], (b - mean) * s + beta))
    return convs, (state['head.weight'].numpy(), state['head.bias'].numpy())


def forward(convs, head, x):
    """x (ch, T) float32 -> logits. Plain loops mirror the C++ so the two can only differ by rounding."""
    for w, b in convs:
        o, i, k = w.shape; pad = k // 2; T = x.shape[1]; Tout = (T + 2 * pad - k) // 2 + 1
        xp = np.zeros((i, T + 2 * pad), np.float32); xp[:, pad:pad + T] = x
        y = np.empty((o, Tout), np.float32)
        for t in range(Tout):
            seg = xp[:, 2 * t:2 * t + k]
            y[:, t] = np.tensordot(w, seg, axes=([1, 2], [0, 1])) + b
        x = np.maximum(y, 0)
    return head[0] @ x.mean(1) + head[1]


def save_npz(path, convs, head, classes, channels, scale=None):
    """Folded weights for numpy inference (emg_live.py): no torch needed at run time."""
    blob = {f'w{l}': w for l, (w, _) in enumerate(convs)} | {f'b{l}': b for l, (_, b) in enumerate(convs)}
    np.savez(path, **blob, head_w=head[0], head_b=head[1], classes=np.array(classes), channels=np.array(channels),
             scale=np.ones(len(channels), np.float32) if scale is None else np.asarray(scale, np.float32))


def load_npz(path):
    z = np.load(path, allow_pickle=False)
    convs = [(z[f'w{l}'], z[f'b{l}']) for l in range(4)]
    return {'convs': convs, 'head': (z['head_w'], z['head_b']), 'classes': [str(c) for c in z['classes']],
            'channels': [int(c) for c in z['channels']], 'scale': z['scale']}


def carr(name, a, ctype='float'):
    flat = np.asarray(a, np.float32).ravel()
    dims = ''.join(f'[{d}]' for d in a.shape)
    body = ','.join(f'{v:.8e}f' for v in flat)
    return f'inline constexpr {ctype} {name}{dims} = {{{body}}};\n'


def emit(convs, head, channels, classes, probe, logits, probe_y, out=HERE / 'device'):
    w_h = ['#pragma once\n// Generated by emg_cnn_export.py from emg_gni_train.py --save; BatchNorm folded. Do not edit.\n',
           f'inline constexpr int emgCnnChannels = {len(channels)}; inline constexpr int emgCnnWindow = {probe.shape[2]}; inline constexpr int emgCnnClasses = {len(classes)};\n',
           'inline constexpr int emgCnnKernel[4] = {' + ','.join(str(k) for k, _ in LAYERS) + '}; inline constexpr int emgCnnOut[4] = {' + ','.join(str(o) for _, o in LAYERS) + '};\n']
    for l, (w, b) in enumerate(convs):
        w_h.append(carr(f'emgCnnW{l}', w)); w_h.append(carr(f'emgCnnB{l}', b))
    w_h.append(carr('emgCnnHeadW', head[0])); w_h.append(carr('emgCnnHeadB', head[1]))
    (out / 'emg_cnn_weights.h').write_text(''.join(w_h))
    i_h = ['#pragma once\n// Probe windows (Meta discrete_gestures test user, normalised) + PyTorch logits; the board must reproduce them.\n',
           f'inline constexpr int emgProbeCases = {len(probe)};\n',
           'inline constexpr const char* emgProbeLabels[' + str(len(probe)) + '] = {' + ','.join(f'"{classes[int(y)]}"' for y in probe_y) + '};\n',
           'inline constexpr const char* emgClassNames[' + str(len(classes)) + '] = {' + ','.join(f'"{c}"' for c in classes) + '};\n',
           carr('emgProbeInput', probe), carr('emgProbeLogits', logits)]
    (out / 'emg_cnn_input.h').write_text(''.join(i_h))
    return sum(w.size + b.size for w, b in convs) + head[0].size + head[1].size


def export(pt):
    import torch
    blob = torch.load(pt, map_location='cpu', weights_only=False)
    convs, head = fold(blob['state'])
    ours = np.stack([forward(convs, head, x) for x in blob['probe']])
    diff = float(np.abs(ours - blob['probe_logits']).max())
    assert diff < 1e-3, f'folded numpy forward differs from torch by {diff}'
    n = emit(convs, head, blob['channels'], blob['classes'], blob['probe'], blob['probe_logits'], blob['probe_y'])
    save_npz(Path(pt).with_suffix('.npz'), convs, head, blob['classes'], blob['channels'])
    np.savez(Path(pt).with_suffix('.probe.npz'), x=blob['probe'], logits=blob['probe_logits'])
    print(f'exported {n} weights, {len(blob["probe"])} probe windows, torch/numpy maxdiff {diff:.2e}')


def check():
    import torch
    from emg_gni_train import Net
    torch.manual_seed(0)
    net = Net(4, 4)
    # Untrained BN has mean 0 / var 1: push random statistics in so folding is actually exercised.
    for m in net.modules():
        if isinstance(m, torch.nn.BatchNorm1d):
            m.running_mean.uniform_(-1, 1); m.running_var.uniform_(.5, 2); m.weight.data.uniform_(.5, 1.5); m.bias.data.uniform_(-1, 1)
    net.eval()
    x = torch.randn(3, 4, 400)
    with torch.no_grad(): ref = net(x).numpy()
    convs, head = fold({k: v for k, v in net.state_dict().items()})
    ours = np.stack([forward(convs, head, xi.numpy()) for xi in x])
    diff = float(np.abs(ours - ref).max())
    assert diff < 1e-3, diff
    # Must fail: unfolded BN (raw conv weights) must NOT match.
    raw = [(net.f[l][0].weight.detach().numpy(), net.f[l][0].bias.detach().numpy()) for l in range(4)]
    assert np.abs(np.stack([forward(raw, head, xi.numpy()) for xi in x]) - ref).max() > 1e-2, 'BN folding made no difference'
    print(f'export check passed: folded numpy == torch (maxdiff {diff:.1e}); unfolded differs')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('pt', nargs='?'); p.add_argument('--check', action='store_true')
    a = p.parse_args()
    check() if a.check or not a.pt else export(a.pt)
